import SwiftUI
import ZIPFoundation
import Darwin
import UniformTypeIdentifiers

@MainActor @Observable final class NativeProjectWorkspace {
    enum Language: String, CaseIterable, Identifiable {
        case swift = "Swift", objectiveC = "Objective-C"
        var id: String { rawValue }
    }
    var language: Language = .swift
    var projectName = "NewNativeApp"
    var source = "import SwiftUI\n@main struct NewNativeApp: App { var body: some Scene { WindowGroup { Text(\"Hello iPhone\") } } }"
    var status = "Edit source, then try the experimental on-device compiler with an installed SDK."
    var output: URL?
    var building = false
    var builtIPA: URL?
    var compilerReport = "Native compilation is unavailable until an iPhoneOS SDK is installed and compiler/linker job execution is verified."
    func checkNativeCompiler() {
        let root = FileManager.default.urls(for:.applicationSupportDirectory,in:.userDomainMask).first!
        let sdk = root.appendingPathComponent("iPhoneOS.sdk")
        compilerReport = NyxianCompilerProbe.inspect(sdkURL:FileManager.default.fileExists(atPath:sdk.path) ? sdk : nil)
    }
    func resetTemplate() {
        switch language {
        case .swift:
            source = "import SwiftUI\n@main struct NewNativeApp: App { var body: some Scene { WindowGroup { Text(\"Hello iPhone\") } } }"
        case .objectiveC:
            source = "#import <UIKit/UIKit.h>\n@interface AppDelegate : UIResponder <UIApplicationDelegate> @end\n@implementation AppDelegate @end\nint main(int argc, char **argv) { @autoreleasepool { return UIApplicationMain(argc, argv, nil, NSStringFromClass([AppDelegate class])); } }"
        }
    }
    func buildNative() {
        guard !building else { return }
        let sourceText = source, projectTitle = projectName, swift = language == .swift
        building = true
        builtIPA = nil
        status = "Compiling and linking on device…"
        Task {
            let result = await Task.detached(priority: .userInitiated) {
                Result { try PocketNativeBuild.build(source: sourceText, name: projectTitle, isSwift: swift) }
            }.value
            building = false
            switch result {
            case .success(let ipa):
                builtIPA = ipa
                status = "Compiler and linker returned success; an ARM64 executable was packaged. It is unsigned and has not been run."
            case .failure(let error):
                status = "Native build failed: " + error.localizedDescription
            }
        }
    }
    func exportProject() {
        do {
            let characters = CharacterSet.alphanumerics.union(CharacterSet(charactersIn:"_-"))
            guard !projectName.isEmpty, projectName.unicodeScalars.allSatisfy({ characters.contains($0) }) else {
                status = "Project name must contain only letters, digits, underscores, or hyphens."
                return
            }
            let manager = FileManager.default
            let root = manager.temporaryDirectory.appendingPathComponent(UUID().uuidString, isDirectory:true)
            defer { try? manager.removeItem(at:root) }
            let folder = root.appendingPathComponent(projectName,isDirectory:true)
            try manager.createDirectory(at:folder,withIntermediateDirectories:true)
            let filename = language == .swift ? "main.swift" : "main.m"
            try source.write(to:folder.appendingPathComponent(filename),atomically:true,encoding:.utf8)
            let readme = """
            Native iPhone source project generated by LocalCoder.
            Language: \(language.rawValue)
            Building requires a compatible native compiler and SDK.
            This archive contains editable source, not a compiled iOS executable.
            You can import or share these files with an iPhone-native IDE such as Nyxian.
            """
            try readme.write(to:folder.appendingPathComponent("README.txt"),atomically:true,encoding:.utf8)
            let zip = manager.temporaryDirectory.appendingPathComponent(projectName+"-"+UUID().uuidString+".zip")
            try manager.zipItem(at:folder,to:zip)
            output = zip
            status = "Native project ZIP created entirely on iPhone. Compiler integration is not installed; source was not compiled."
        } catch { status = error.localizedDescription }
    }
}
struct NativeCompilerView: View {
    @State private var project = NativeProjectWorkspace()
    var body: some View {
        NavigationStack {
            VStack(alignment:.leading,spacing:10) {
                Picker("Language",selection:$project.language) {
                    ForEach(NativeProjectWorkspace.Language.allCases) { language in Text(language.rawValue).tag(language) }
                }.pickerStyle(.segmented)
                .onChange(of:project.language) { _, _ in project.resetTemplate() }
                TextField("Project name", text:$project.projectName).textFieldStyle(.roundedBorder)
                TextEditor(text:$project.source)
                    .font(.system(size:12,design:.monospaced))
                    .textInputAutocapitalization(.never)
                    .autocorrectionDisabled()
                Text(project.status).font(.caption).foregroundStyle(.secondary)
                Button("Check local native toolchain") { project.checkNativeCompiler() }.buttonStyle(.bordered)
                Text(project.compilerReport).font(.caption).foregroundStyle(.secondary).textSelection(.enabled)
                Text("To install an SDK, open the SDK tab under More. Project export is not compilation.").font(.caption).foregroundStyle(.secondary)
                Button("Build unsigned native IPA") { project.buildNative() }.buttonStyle(.borderedProminent).disabled(project.building)
                if project.building { ProgressView("Building on iPhone…") }
                if let ipa = project.builtIPA { ShareLink(item: ipa) { Label("Save unsigned native IPA", systemImage: "square.and.arrow.up") } }
                HStack {
                    Button("Export native project") { project.exportProject() }.buttonStyle(.borderedProminent)
                    if let output=project.output { ShareLink(item:output) { Label("Save", systemImage:"square.and.arrow.up") } }
                }
                Link("On-device compiler project: Nyxian",destination:URL(string:"https://github.com/emexlab/Nyxian")!)
                    .font(.footnote)
            }
            .padding()
            .navigationTitle("Native Code")
        }
    }
}
